#: Обратный словарь: английское имя → русское.
ОБРАТНЫЕ: dict[str, str] = {англ: рус for рус, англ in СИНОНИМЫ.items()}

#: Типы файлов раскладки на двух языках.
ТИПЫ: dict[str, str] = {
    "текст": "text", "записка": "note", "журнал": "log",
    "реверс": "reversed", "перестановка_строк": "reordered",
    "gzip": "gzip", "zip": "zip", "tar": "tar", "png": "png",
    "base64": "base64", "xor": "xor",
}
ТИПЫ_ОБРАТНЫЕ: dict[str, str] = {англ: рус for рус, англ in ТИПЫ.items()}


def имена(ключ: str) -> tuple[str, ...]:
    """Все написания ключа: как передали плюс синоним на другом языке."""
    варианты = [ключ]
    if ключ in СИНОНИМЫ:
        варианты.append(СИНОНИМЫ[ключ])
    if ключ in ОБРАТНЫЕ:
        варианты.append(ОБРАТНЫЕ[ключ])
    return tuple(dict.fromkeys(варианты))


def поле(данные: Any, ключ: str, умолчание: Any = None) -> Any:
    """Значение по ключу на любом из двух языков."""
    if not isinstance(данные, dict):
        return умолчание
    for имя in имена(ключ):
        if имя in данные:
            return данные[имя]
    return умолчание


def есть(данные: Any, ключ: str) -> bool:
    return isinstance(данные, dict) and any(имя in данные for имя in имена(ключ))


def тип_файла(значение: str) -> str:
    """Приводит тип файла раскладки к русскому написанию (оно каноническое)."""
    значение = str(значение or "").strip()
    return ТИПЫ_ОБРАТНЫЕ.get(значение, значение)


#: Значения состояния комнаты на двух языках.
СОСТОЯНИЯ: dict[str, str] = {"активно": "active", "неактивно": "inactive"}
СОСТОЯНИЯ_ОБРАТНЫЕ: dict[str, str] = {а: р for р, а in СОСТОЯНИЯ.items()}


def канон_состояния(значение: Any) -> str:
    """Приводит состояние комнаты к русскому написанию (оно каноническое)."""
    строка = str(значение or "").strip()
    return СОСТОЯНИЯ_ОБРАТНЫЕ.get(строка, строка)


def язык(данные: Any) -> str:
    """На каком языке написаны ключи этого словаря: «ru» или «en».

    Нужно при записи: в английском пакете движок не должен оставлять после
    себя кириллические ключи, и наоборот.
    """
    if not isinstance(данные, dict):
        return "ru"
    английских = sum(1 for ключ in данные if ключ in ОБРАТНЫЕ)
    русских = sum(1 for ключ in данные if ключ in СИНОНИМЫ)
    return "en" if английских > русских else "ru"


def имя_для(ключ: str, язык_данных: str = "ru") -> str:
    """Как назвать ключ в файле на этом языке."""
    if язык_данных == "en":
        return СИНОНИМЫ.get(ключ, ОБРАТНЫЕ.get(ключ, ключ) if ключ in ОБРАТНЫЕ else ключ)
    return ОБРАТНЫЕ.get(ключ, ключ)


def записать(данные: dict, ключ: str, значение: Any) -> None:
    """Пишет значение под тем именем, которое уже есть в словаре.

    Если такого ключа ещё не было — под именем на языке этого словаря.
    """
    for имя in имена(ключ):
        if имя in данные:
            данные[имя] = значение
            return
    данные[имя_для(ключ, язык(данные))] = значение


def запись(образец: dict, поля: dict) -> dict:
    """Словарь с именами ключей на языке образца.

    Движок дописывает в файл мира историю применённых действий; в английском
    пакете её ключи должны быть английскими.
    """
    язык_данных = язык(образец)
    return {имя_для(ключ, язык_данных): значение for ключ, значение in поля.items()}


def значение_состояния(данные: dict, состояние: str) -> str:
    """Состояние комнаты на языке пакета: «активно» или «active»."""
    return СОСТОЯНИЯ[состояние] if язык(данные) == "en" else состояние


def нормализовать(данные: Any, ключи: Iterable[str] | None = None) -> dict:
    """Копия словаря с русскими ключами — удобно для единообразной обработки."""
    if not isinstance(данные, dict):
        return {}
    итог = {}
    for ключ, значение in данные.items():
        итог[ОБРАТНЫЕ.get(ключ, ключ)] = значение
    return итог
