"""Озвучка реплик разума (возможность «озвучка»).

Механический голос из динамика добавляет к сцене больше, чем любой текстовый
эффект. Приложение ничего не устанавливает и никуда не ходит: оно ищет уже
имеющийся в системе синтезатор речи и запускает его отдельным процессом, не
задерживая игру.

Поддерживаются штатные для Linux синтезаторы. Если ни одного нет, возможность
считается недоступной: пусковое окно покажет это и предложит установить,
а квест продолжит работать молча.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import threading
from typing import Any

#: Известные синтезаторы: имя → как построить команду.
#: ``скорость`` — слов в минуту, ``высота`` — 0..99 (чем ниже, тем «машиннее»).
ДВИЖКИ: dict[str, dict[str, Any]] = {
    "espeak-ng": {
        "аргументы": ["-v", "{голос}", "-s", "{скорость}", "-p", "{высота}", "--", "{текст}"],
        "голос": "ru",
        "описание": "espeak-ng — механический голос, лучше всего подходит комплексу",
    },
    "espeak": {
        "аргументы": ["-v", "{голос}", "-s", "{скорость}", "-p", "{высота}", "--", "{текст}"],
        "голос": "ru",
        "описание": "espeak — то же самое, версия постарше",
    },
    "spd-say": {
        "аргументы": ["-l", "ru", "-r", "{скорость_spd}", "-w", "{текст}"],
        "голос": "ru",
        "описание": "spd-say — обёртка speech-dispatcher",
    },
    "festival": {
        "аргументы": ["--tts"],
        "через_ввод": True,
        "голос": "",
        "описание": "festival — читает текст со стандартного ввода",
    },
}

#: Что не нужно произносить: рамки, точки-заполнители, служебные пометки.
_МУСОР = re.compile(r"[─│┌┐└┘├┤╔╗╚╝═║•]+|\.{3,}|_{3,}|-{3,}")


def найти_движок(предпочтительный: str = "") -> tuple[str, str] | None:
    """Возвращает (имя, путь) первого найденного синтезатора или ``None``."""
    порядок = [предпочтительный] if предпочтительный else []
    порядок += [имя for имя in ДВИЖКИ if имя != предпочтительный]
    for имя in порядок:
        if not имя or имя not in ДВИЖКИ:
            continue
        путь = shutil.which(имя)
        if путь:
            return имя, путь
    return None


def подготовить_текст(текст: str, предел: int = 600) -> str:
    """Чистит реплику от того, что вслух звучит бессмысленно."""
    очищенный = _МУСОР.sub(" ", текст or "")
    очищенный = re.sub(r"\s+", " ", очищенный).strip()
    return очищенный[:предел]


def собрать_команду(имя: str, путь: str, текст: str, скорость: int = 150,
                    высота: int = 25, голос: str = "") -> list[str]:
    """Строит командную строку для найденного синтезатора."""
    описание = ДВИЖКИ[имя]
    подстановки = {
        "{текст}": текст,
        "{голос}": голос or описание.get("голос", ""),
        "{скорость}": str(скорость),
        # spd-say принимает скорость в диапазоне -100..100
        "{скорость_spd}": str(max(-100, min(100, int((скорость - 150) / 2)))),
        "{высота}": str(высота),
    }
    аргументы = [подстановки.get(а, а) for а in описание.get("аргументы", [])]
    return [путь, *аргументы]


class Голос:
    """Произносит реплики разума, не задерживая игру."""

    def __init__(self, cfg: dict | None = None):
        настройки = (cfg or {}).get("voice", {}) if cfg else {}
        self.скорость = int(настройки.get("скорость", 150))
        self.высота = int(настройки.get("высота", 25))
        self.голос = str(настройки.get("голос", ""))
        self.предел = int(настройки.get("предел_символов", 600))
        найдено = найти_движок(str(настройки.get("движок", "")))
        self.имя, self.путь = найдено if найдено else ("", "")
        self._процесс: subprocess.Popen | None = None
        self._замок = threading.Lock()

    @property
    def доступен(self) -> bool:
        return bool(self.путь)

    def произнести(self, текст: str, ждать: bool = False) -> bool:
        """Запускает синтезатор. Возвращает False, если произносить нечем."""
        if not self.доступен:
            return False
        подготовленный = подготовить_текст(текст, self.предел)
        if not подготовленный:
            return False
        команда = собрать_команду(self.имя, self.путь, подготовленный,
                                  self.скорость, self.высота, self.голос)
        через_ввод = ДВИЖКИ[self.имя].get("через_ввод", False)
        with self._замок:
            self.замолчать()
            try:
                self._процесс = subprocess.Popen(
                    команда,
                    stdin=subprocess.PIPE if через_ввод else subprocess.DEVNULL,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
            except OSError:
                self._процесс = None
                return False
            if через_ввод and self._процесс.stdin is not None:
                try:
                    self._процесс.stdin.write(подготовленный.encode("utf-8"))
                    self._процесс.stdin.close()
                except OSError:
                    pass
        if ждать:
            self.дождаться()
        return True

    def дождаться(self, таймаут: float | None = None) -> None:
        процесс = self._процесс
        if процесс is not None:
            try:
                процесс.wait(timeout=таймаут)
            except subprocess.TimeoutExpired:
                pass

    def замолчать(self) -> None:
        """Обрывает недоговорённую реплику — например, при новой."""
        процесс = self._процесс
        if процесс is not None and процесс.poll() is None:
            try:
                процесс.terminate()
            except OSError:
                pass
        self._процесс = None

    def описание(self) -> str:
        if not self.доступен:
            return "синтезатор речи не найден"
        return f"{self.имя} ({ДВИЖКИ[self.имя]['описание']})"
