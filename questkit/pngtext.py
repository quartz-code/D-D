GLYPH_W, GLYPH_H = 5, 7
UNKNOWN = ("#####", "#####", "#####", "#####", "#####", "#####", "#####")


def _glyph(char: str) -> tuple[str, ...]:
    return FONT.get(char.upper(), UNKNOWN)


def render_text(lines: list[str], scale: int = 6, padding: int = 10,
                ink: int = 0xF2, paper: int = 0x14) -> tuple[int, int, bytearray]:
    """Растеризует строки в 8-битное полутоновое изображение."""
    scale = max(1, int(scale))
    columns = max((len(line) for line in lines), default=1)
    text_w = columns * (GLYPH_W + 1) - 1
    text_h = len(lines) * (GLYPH_H + 2) - 2
    width = text_w * scale + padding * 2
    height = text_h * scale + padding * 2

    pixels = bytearray([paper]) * (width * height)
    for row_index, line in enumerate(lines):
        base_y = padding + row_index * (GLYPH_H + 2) * scale
        for col_index, char in enumerate(line):
            glyph = _glyph(char)
            base_x = padding + col_index * (GLYPH_W + 1) * scale
            for gy, row in enumerate(glyph):
                for gx, cell in enumerate(row):
                    if cell != "#":
                        continue
                    for sy in range(scale):
                        y = base_y + gy * scale + sy
                        if y >= height:
                            continue
                        offset = y * width + base_x + gx * scale
                        for sx in range(scale):
                            x = base_x + gx * scale + sx
                            if x < width:
                                pixels[offset + sx] = ink
    return width, height, pixels


def _chunk(tag: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + tag + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))


def _itxt(keyword: str, text: str) -> bytes:
    """Текстовый чанк в UTF-8 (виден командой strings)."""
    payload = (keyword.encode("latin-1", "replace") + b"\x00"
               + b"\x00\x00"          # без сжатия
               + b"\x00"              # язык не указан
               + b"\x00"              # перевод ключевого слова не указан
               + text.encode("utf-8"))
    return _chunk(b"iTXt", payload)


def write_png(path: str | Path, lines: list[str], notes: dict[str, str] | None = None,
              scale: int = 6) -> Path:
    """Пишет PNG с надписью и текстовыми заметками внутри."""
    path = Path(path)
    width, height, pixels = render_text(lines, scale=scale)

    raw = bytearray()
    for y in range(height):
        raw.append(0)  # тип фильтра «none»
        raw.extend(pixels[y * width:(y + 1) * width])

    png = bytearray(b"\x89PNG\r\n\x1a\n")
    png += _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0))
    for keyword, text in (notes or {}).items():
        png += _itxt(keyword, text)
    png += _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += _chunk(b"IEND", b"")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(bytes(png))
    return path
